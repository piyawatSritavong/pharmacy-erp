import { chromium } from "playwright";
const BASE = "http://localhost:3000";
const b = await chromium.launch();
const p = await b.newPage({ viewportSize: { width: 1440, height: 1000 } });
await p.goto(BASE + "/login", { waitUntil: "networkidle" });
await p.getByLabel("อีเมล").fill("superadmin@erp.local");
await p.getByLabel("รหัสผ่าน").fill("DevPassword123!");
await Promise.all([p.waitForResponse((r) => r.url().includes("/auth/login")), p.getByRole("button", { name: "เข้าสู่ระบบ" }).click()]);
await p.waitForURL((u) => !u.pathname.includes("/login"));
await p.goto(BASE + "/audit", { waitUntil: "domcontentloaded" });
await p.waitForTimeout(3000);
const rawJson = await p.evaluate(() => document.body.innerText.includes('{"') || document.body.innerText.includes('": '));
console.log("audit still shows raw JSON:", rawJson);
await p.screenshot({ path: process.env.SHOT_DIR + "/audit-readable.png", fullPage: false });
await p.goto(BASE + "/sales-history", { waitUntil: "domcontentloaded" });
await p.waitForTimeout(3000);
console.log("sales-history branch filter:", await p.getByLabel("กรองตามสาขา").count());
const nums = await p.locator("table tbody tr td:first-child").allInnerTexts();
console.log("first 6 invoice numbers:", nums.slice(0,6).join(", "));
await p.screenshot({ path: process.env.SHOT_DIR + "/sales-history-branch.png", fullPage: false });
await b.close();
